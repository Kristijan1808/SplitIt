export type TranslationKey = keyof (typeof translations)["hr"];

const STORAGE_KEY = "splitit:locale";
const listeners = new Set<() => void>();

export const getStoredLanguage = (): LanguageCode => {
  if (typeof window === "undefined") return "hr";
  const stored = window.localStorage.getItem(STORAGE_KEY) as LanguageCode | null;
  if (stored && languageOptions.some((option) => option.code === stored)) {
    return stored;
  }
  return "hr";
};

export const setStoredLanguage = (language: LanguageCode) => {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(STORAGE_KEY, language);
  }
  listeners.forEach((listener) => listener());
};

export const getLanguageLocale = (language: LanguageCode) =>
  languageOptions.find((option) => option.code === language)?.locale ?? "hr-HR";

export const formatLocalizedDateTime = (dateString: string | null | undefined, language: LanguageCode) => {
  if (!dateString) return "";

  const date = new Date(dateString);
  if (Number.isNaN(date.getTime())) return "";

  return new Intl.DateTimeFormat(getLanguageLocale(language), {
    dateStyle: "medium",
    timeStyle: "short"
  }).format(date);
};

export const languageService = {
  subscribe: (listener: () => void) => {
    listeners.add(listener);
    return () => listeners.delete(listener);
  },
  getSnapshot: () => getStoredLanguage(),
  setLanguage: (language: LanguageCode) => {
    setStoredLanguage(language);
  }
};

export const useLanguage = () => {
  const language = useSyncExternalStore(
    languageService.subscribe,
    languageService.getSnapshot,
    languageService.getSnapshot
  );

  return {
    language,
    locale: getLanguageLocale(language),
    languages: languageOptions,
    t: (key: TranslationKey) => translations[language][key],
    setLanguage: (nextLanguage: LanguageCode) => languageService.setLanguage(nextLanguage)
  };
};
